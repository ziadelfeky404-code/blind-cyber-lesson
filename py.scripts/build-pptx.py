from pptx.oxml.ns import qn
from lxml import etree

EMU_PER_PX = 914400 // 96


def px(v):
    return Emu(int(v * EMU_PER_PX))


def add_text(slide, left, top, width, height, text, size, bold, rgb):
    tb = slide.shapes.add_textbox(px(left), px(top), px(width), px(height))
    tf = tb.text_frame
    tf.word_wrap = True
    for i, line in enumerate(text.split("\n")):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        run = p.add_run()
        run.text = line
        run.font.size = Pt(size)
        run.font.bold = bold
        run.font.name = "Arial"
        run.font.color.rgb = RGBColor(*rgb)
        pPr = p._p.get_or_add_pPr()
        pPr.set("rtl", "1")
        pPr.set("algn", "r")
        rPr = run._r.get_or_add_rPr()
        for tag in ("a:ea", "a:cs"):
            el = etree.SubElement(rPr, qn(tag))
            el.set("typeface", "Arial")
    tb._element.nvSpPr.cNvPr.set("descr", text[:900])
    return tb


def add_slide(prs, title, body, notes):
    slide = prs.slides.add_slide(prs.slide_layouts[6])
    add_text(slide, 40, 26, 880, 70, title, 28, True, (0x0B, 0x3D, 0x6B))
    add_text(slide, 40, 104, 880, 400, body, 18, False, (0x1A, 0x1A, 0x1A))
    slide.notes_slide.notes_text_frame.text = notes
    return slide


