AR_LETTER = r"[\u0621-\u064A]"
AR_MARK = r"[\u064B-\u0652]"


def _word_re(word):
    return re.compile("(?<!" + AR_LETTER + ")" + re.escape(word) + "(?!" + AR_LETTER + "|" + AR_MARK + ")")


_LATIN_RE = [(re.compile(re.escape(a), re.IGNORECASE), b) for a, b in LATIN]
_TASHKEEL_RE = [(re.compile(re.escape(a)), b) for a, b in TASHKEEL]
_FEM_RE = [(_word_re(a), b) for a, b in FEM]
_K_RE = [(_word_re(w), w + "\u0650") for w in K_SUFFIX]


def normalize(text):
    """يحوّل النص المكتوب إلى نص صالح للنطق (بلا بريد أو أرقام أو حروف لاتينية)."""
    for old, new in SPOKEN_FIXES:
        text = text.replace(old, new)
    for rx, rep in _LATIN_RE:
        text = rx.sub(rep, text)
    text = re.sub(r"\S+@\S+", "", text)          # أي بريد متبقٍّ لا يُنطق
    for rx, rep in _TASHKEEL_RE:
        text = rx.sub(rep, text)
    text = text.replace("\u200f", " ").replace("\u200e", " ")
    text = re.sub(r"\.{2,}", ".", text)
    text = re.sub(r"([:؟!])\s*\.", r"\1 ", text)
    text = re.sub(r"\s*([،؛:.!؟])\s*", r"\1 ", text)
    text = re.sub(r"\s+", " ", text).strip()
    if text and text[-1] not in ".!؟":
        text += "."
    return text


def feminize(text):
    for rx, rep in _FEM_RE:
        text = rx.sub(rep, text)
    for rx, rep in _K_RE:
        text = rx.sub(rep, text)
    return text


def variants(text):
    """النص بصيغتين: مذكر كما هو، ومؤنث بكل كلمة تخاطب المتعلم."""
    base = normalize(text)
    return {"m": base, "f": normalize(feminize(base))}


def text_hash(text):
    return hashlib.sha1(text.encode("utf-8")).hexdigest()[:16]


def load_cache(path):
    try:
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    except (OSError, ValueError):
        return {}


def save_cache(path, data):
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=0, sort_keys=True)


def needs_build(cache, voice, key, text, file_path, min_size=1200):
    """يُبنى المقطع إذا كان الملف مفقودًا أو صغيرًا أو تغيّر نصه."""
    if not os.path.exists(file_path) or os.path.getsize(file_path) < min_size:
        return True
    return cache.get(voice, {}).get(key) != text_hash(text)


def mark_built(cache, voice, key, text):
    cache.setdefault(voice, {})[key] = text_hash(text)


def unused_rules(pairs, corpus):
    """قواعد لم تُطبَّق في أي نص — غالبًا خطأ إملائي في القاعدة نفسها."""
    missing = []
    for masc, _ in pairs:
        rx = _word_re(masc)
        if not any(rx.search(t) for t in corpus):
            missing.append(masc)
    return missing
