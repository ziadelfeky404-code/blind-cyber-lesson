function Add-TextShape($slide, $x, $y, $w, $h, $text, $size, $bold, $rgb) {
  $box = $slide.Shapes.AddTextbox(1, $x, $y, $w, $h)
  $tf2 = $box.TextFrame2
  $tf2.TextRange.Text = $text
  $tf2.TextRange.Font.Size = $size
  $tf2.TextRange.Font.Bold = $(if ($bold) { -1 } else { 0 })
  $tf2.TextRange.Font.Name = 'Arial'
  $tf2.TextRange.Font.Fill.ForeColor.RGB = $rgb
  $tf2.TextRange.ParagraphFormat.Alignment = 3
  $tf2.TextRange.ParagraphFormat.RTL = -1
  $tf2.WordWrap = -1
  $box.TextFrame.WordWrap = -1
  $box.AlternativeText = $text
  return $box
}

function New-Slide($pres, $title, $bodyText, $notes) {
  $slide = $pres.Slides.Add($pres.Slides.Count + 1, 12)
  [void](Add-TextShape $slide 40 26 880 66 $title 28 (-1) 0x0B3D6B)
  [void](Add-TextShape $slide 40 104 880 404 $bodyText 20 0 0x1A1A1A)
  if ($notes) { $slide.NotesPage.Shapes.Placeholders(2).TextFrame.TextRange.Text = $notes }
  return $slide
}

