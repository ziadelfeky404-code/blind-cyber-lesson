def file_for(voice_key: str, key: str) -> Path:
    return OUT_DIR / voice_key / (key.replace(".", "_") + ".mp3")


# مؤثرات صوتية حقيقية مولّدة بـ ffmpeg (ليست تلاوة آلية) — مشتركة بين الصوتين
SFX = {
    "sfx.clap": "audio/hub/clap.mp3",
    "sfx.buzz": "audio/hub/buzz.mp3",
}


async def synth(voice_key: str, key: str, text: str, force: bool, cache: dict) -> str:
    from edge_tts import Communicate
    path = file_for(voice_key, key)
    path.parent.mkdir(parents=True, exist_ok=True)
    if not force and not voice.needs_build(cache, voice_key, key, text, str(path)):
        return "skip"
    # الخدمة ترفض أحيانًا تحت الضغط ("No audio was received") — نعيد المحاولة بتباعد متزايد
    # والصوت المذكر أبطأ من المؤنث في النصوص الطويلة (46 ثانية لنص ١١٦٤ حرفًا)،
    # لذا المهلة تتناسب مع طول النص بدل حدٍّ ثابت كان يقطع المقاطع الطويلة.
    last = ""
    timeout = 45 if len(text) > 700 else 30
    for attempt in range(4):
        try:
            communicate = Communicate(text, voice=voice.VOICES[voice_key], rate=voice.RATE)
            await asyncio.wait_for(communicate.save(str(path)), timeout=timeout)
            if path.stat().st_size < 1200:
                path.unlink(missing_ok=True)
                last = "empty file"
            else:
                voice.mark_built(cache, voice_key, key, text)
                return "ok"
        except Exception as exc:
            last = str(exc)
        if path.exists():
            try:
                path.unlink()
            except OSError:
                pass
        await asyncio.sleep(1.5 * (attempt + 1))
    print(f"  !! {key}: {last}")
    return "fail"


def write_manifest() -> int:
    html = SITE.read_text(encoding="utf-8")
    start = html.index(START)
    end = html.index(END, start)
    entries = {}
    for vk in voice.VOICES:
        entries[vk] = {k: f"audio/hub/{vk}/" + k.replace(".", "_") + ".mp3" for k in TEXTS}
        entries[vk].update(SFX)
    manifest = "const HUB_AUDIO = " + json.dumps(entries, ensure_ascii=False, indent=2) + ";"
    new_html = html[:start + len(START)] + "\n" + manifest + "\n" + html[end:]
    SITE.write_text(new_html, encoding="utf-8")
    return len(entries["m"])


async def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--force", action="store_true")
    parser.add_argument("--only", default=None)
    parser.add_argument("--voice", choices=["m", "f", "all"], default="all")
    args = parser.parse_args()

    keys = list(TEXTS.keys())
    if args.only:
        keys = [k for k in keys if k in args.only.split(",")]

    voices = list(voice.VOICES) if args.voice == "all" else [args.voice]

    if args.dry_run:
        for k in keys:
            v = voice.variants(TEXTS[k])
            print(k)
            print("  م:", v["m"][:100])
            print("  ف:", v["f"][:100])
        return 0

    cache = voice.load_cache(str(CACHE))
    made = skipped = failed = 0
    # كل مقطع يستغرق ثواني على الشبكة؛ أربعة معًا تقصّر الوقت بلا أخطاء
    sem = asyncio.Semaphore(4)

    async def one(vk, key, n):
        async with sem:
            text = voice.variants(TEXTS[key])[vk]
            res = await synth(vk, key, text, args.force, cache)
        print(f"  [{n}/{len(keys)}] {vk} {key} -> {res}", flush=True)
        return res

    for vk in voices:
        print(f"\n== صوت {voice.VOICE_LABEL[vk]} ({voice.VOICES[vk]}) ==")
        results = await asyncio.gather(*(one(vk, k, i) for i, k in enumerate(keys, 1)))
        made += results.count("ok")
        skipped += results.count("skip")
        failed += results.count("fail")
        voice.save_cache(str(CACHE), cache)

    total = write_manifest()
    size = sum(p.stat().st_size for p in OUT_DIR.rglob("*.mp3")) / 1024 / 1024
    print(f"\nتم: {made} جديد، {skipped} موجود، {failed} فشل | مانيفست: {total} مفتاح لكل صوت | الحجم: {size:.1f} ميجا")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
